package main

import (
	"fmt"
	"sort"
	"strings"

	"github.com/gotd/td/gen"
	"github.com/gotd/tl"
)

// Field kinds.
const (
	gkPrim = iota
	gkObj
	gkVecPrim
	gkVecObj
)

// gField is one generated field.
type gField struct {
	TL     string
	Go     string
	Kind   int
	Func   string
	GoType string
	Iface  bool
	Word   int
	Bit    int
	BFlag  bool
}

// goGen emits private Go types.
type goGen struct {
	u   *gen.Uni
	buf strings.Builder
}

// pascal converts snake to Camel.
func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up {
			b.WriteString(strings.ToUpper(string(r)))
			up = false
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// primType maps TL primitive.
func primType(name string) (string, string, bool) {
	switch name {
	case "int", "int32":
		return "Int", "int", true
	case "long", "int64":
		return "Long", "int64", true
	case "int53":
		return "Int53", "int64", true
	case "int128":
		return "Int128", "bin.Int128", true
	case "int256":
		return "Int256", "bin.Int256", true
	case "double":
		return "Double", "float64", true
	case "string":
		return "String", "string", true
	case "bytes":
		return "Bytes", "[]byte", true
	case "Bool", "bool":
		return "Bool", "bool", true
	}
	return "", "", false
}

// classType resolves a class reference.
func (g *goGen) classType(name string) (string, bool, bool) {
	if goName, iface := g.u.ClassGoName(name); goName != "" {
		return "tg." + goName, iface, true
	}
	if d, ok := g.u.CanonDef(name); ok {
		return "tg." + pascal(d.Name), false, true
	}
	return "", false, false
}

// field builds one field.
func (g *goGen) field(p tl.Parameter, word int) (gField, error) {
	f := gField{TL: p.Name, Go: pascal(p.Name), Word: word, Bit: -1}
	if p.Flag != nil {
		f.Bit = p.Flag.Index
	}
	t := p.Type
	if t.GenericArg != nil && (t.Name == "vector" || t.Name == "Vector") {
		elem := *t.GenericArg
		if fn, gt, ok := primType(elem.Name); ok {
			f.Kind = gkVecPrim
			f.Func = fn
			f.GoType = "[]" + gt
			return f, nil
		}
		name := elem.String()
		if elem.Percent {
			name = name[1:]
		}
		gt, iface, ok := g.classType(name)
		if !ok {
			return f, fmt.Errorf("vector elem %s", elem.String())
		}
		f.Kind = gkVecObj
		f.GoType = "[]" + gt
		f.Iface = iface
		return f, nil
	}
	if t.Name == "true" && p.Flag != nil {
		f.Kind = gkPrim
		f.Func = "Bool"
		f.GoType = "bool"
		f.BFlag = true
		return f, nil
	}
	if fn, gt, ok := primType(t.Name); ok {
		f.Kind = gkPrim
		f.Func = fn
		f.GoType = gt
		return f, nil
	}
	name := t.String()
	if t.Percent {
		name = name[1:]
	}
	gt, iface, ok := g.classType(name)
	if !ok {
		return f, fmt.Errorf("field %s type %s", p.Name, t.String())
	}
	f.Kind = gkObj
	f.GoType = gt
	f.Iface = iface
	return f, nil
}

// zeroExpr returns encode condition.
func zeroExpr(f gField) string {
	switch f.Kind {
	case gkPrim:
		switch f.GoType {
		case "string":
			return "p." + f.Go + ` != ""`
		case "bool":
			return "p." + f.Go
		case "[]byte":
			return "p." + f.Go + " != nil"
		}
		return "p." + f.Go + " != 0"
	case gkVecPrim, gkVecObj:
		return "len(p." + f.Go + ") > 0"
	}
	if f.Iface {
		return "p." + f.Go + " != nil"
	}
	return "!p." + f.Go + ".Zero()"
}

// emit writes generated types.
func (g *goGen) emit(defs map[uint32]tl.Definition, items []gen.PrivItem) (string, error) {
	g.buf.WriteString("// Code generated by cmd/layandroid, DO NOT EDIT.\n\n")
	g.buf.WriteString("package layerx\n\n")
	g.buf.WriteString("import (\n\t\"github.com/gotd/td/bin\"\n\t\"github.com/gotd/td/tg\"\n)\n\n")
	g.buf.WriteString("var (\n\t_ = bin.Buffer{}\n\t_ = tg.User{}\n)\n\n")
	sort.Slice(items, func(i, j int) bool { return items[i].Go < items[j].Go })
	for _, it := range items {
		var id uint64
		fmt.Sscanf(it.ID, "%x", &id)
		d, ok := defs[uint32(id)]
		if !ok {
			continue
		}
		if err := g.emitOne(it, &d); err != nil {
			return "", fmt.Errorf("%s: %w", it.Go, err)
		}
	}
	g.buf.WriteString("// newPriv allocates a private type.\n")
	g.buf.WriteString("func newPriv(s Sym) bin.Object {\n\tswitch s {\n")
	for _, it := range items {
		g.buf.WriteString("\tcase Sym" + it.Go + ":\n\t\treturn new(" + it.Go + ")\n")
	}
	g.buf.WriteString("\t}\n\treturn nil\n}\n")
	return g.buf.String(), nil
}

// emitOne writes one type.
func (g *goGen) emitOne(it gen.PrivItem, d *tl.Definition) error {
	var (
		fields []gField
		words  = map[string]int{}
	)
	for _, p := range d.Params {
		if p.Flags {
			if _, ok := words[p.Name]; !ok {
				words[p.Name] = len(words)
			}
			continue
		}
		w := -1
		if p.Flag != nil {
			w = words[p.Flag.Name]
		}
		f, err := g.field(p, w)
		if err != nil {
			return err
		}
		fields = append(fields, f)
	}
	g.buf.WriteString("// " + it.Go + " is " + it.Name + ".\n")
	g.buf.WriteString("type " + it.Go + " struct {\n")
	for name := range words {
		g.buf.WriteString("\t" + pascal(name) + " bin.Fields\n")
	}
	for _, f := range fields {
		g.buf.WriteString("\t" + f.Go + " " + f.GoType + "\n")
	}
	g.buf.WriteString("}\n\n")
	g.buf.WriteString(fmt.Sprintf("// TypeID returns client id.\nfunc (*%s) TypeID() uint32 { return 0x%x }\n\n", it.Go, d.ID))
	g.buf.WriteString(fmt.Sprintf("// TypeName returns TL name.\nfunc (*%s) TypeName() string { return %q }\n\n", it.Go, it.Name))
	g.buf.WriteString(fmt.Sprintf("// Encode implements bin.Encoder.\nfunc (p *%s) Encode(b *bin.Buffer) error {\n\tb.PutID(0x%x)\n\treturn p.encodePriv(b, Canon)\n}\n\n", it.Go, d.ID))
	g.buf.WriteString(fmt.Sprintf("// EncodeBare implements bin.BareEncoder.\nfunc (p *%s) EncodeBare(b *bin.Buffer) error { return p.encodePriv(b, Canon) }\n\n", it.Go))
	g.buf.WriteString(fmt.Sprintf("// Decode implements bin.Decoder.\nfunc (p *%s) Decode(b *bin.Buffer) error {\n\tif err := b.ConsumeID(0x%x); err != nil {\n\t\treturn err\n\t}\n\treturn p.decodePriv(b, Canon)\n}\n\n", it.Go, d.ID))
	g.buf.WriteString(fmt.Sprintf("// DecodeBare implements bin.BareDecoder.\nfunc (p *%s) DecodeBare(b *bin.Buffer) error { return p.decodePriv(b, Canon) }\n\n", it.Go))
	g.emitEncode(it, d, fields, words)
	g.emitDecode(it, d, fields, words)
	return nil
}

// emitEncode writes encodePriv.
func (g *goGen) emitEncode(it gen.PrivItem, d *tl.Definition, fields []gField, words map[string]int) {
	b := &g.buf
	fmt.Fprintf(b, "func (p *%s) encodePriv(b *bin.Buffer, l Layer) error {\n", it.Go)
	for name := range words {
		fmt.Fprintf(b, "\tp.%s = 0\n", pascal(name))
	}
	for _, f := range fields {
		if f.Bit < 0 {
			continue
		}
		word := "Flags"
		if f.Word == 1 {
			word = "Flags2"
		}
		if f.BFlag {
			fmt.Fprintf(b, "\tif p.%s {\n\t\tp.%s.Set(%d)\n\t}\n", f.Go, word, f.Bit)
			continue
		}
		fmt.Fprintf(b, "\tif %s {\n\t\tp.%s.Set(%d)\n\t}\n", zeroExpr(f), word, f.Bit)
	}
	idx := 0
	for _, p := range d.Params {
		if p.Flags {
			word := "Flags"
			if idx == 1 {
				word = "Flags2"
			}
			fmt.Fprintf(b, "\tb.PutUint32(uint32(p.%s))\n", word)
			idx++
			continue
		}
		f := fieldByTL(fields, p.Name)
		if f == nil {
			continue
		}
		if f.Bit >= 0 && !f.BFlag {
			word := "Flags"
			if f.Word == 1 {
				word = "Flags2"
			}
			fmt.Fprintf(b, "\tif p.%s.Has(%d) {\n", word, f.Bit)
			g.emitWrite(f, "\t\t")
			fmt.Fprintf(b, "\t}\n")
			continue
		}
		g.emitWrite(f, "\t")
	}
	b.WriteString("\treturn nil\n}\n\n")
}

// fieldByTL finds a field.
func fieldByTL(fields []gField, name string) *gField {
	for i := range fields {
		if fields[i].TL == name {
			return &fields[i]
		}
	}
	return nil
}

// emitWrite writes one value.
func (g *goGen) emitWrite(f *gField, ind string) {
	b := &g.buf
	expr := "p." + f.Go
	switch f.Kind {
	case gkPrim:
		if f.BFlag {
			return
		}
		fmt.Fprintf(b, "%sb.Put%s(%s)\n", ind, f.Func, expr)
	case gkObj:
		arg := expr
		if !f.Iface {
			arg = "&" + expr
		}
		fmt.Fprintf(b, "%sif err := putObj(b, l, %s); err != nil {\n%s\treturn err\n%s}\n", ind, arg, ind, ind)
	case gkVecPrim:
		fmt.Fprintf(b, "%sb.PutVectorHeader(len(%s))\n", ind, expr)
		fmt.Fprintf(b, "%sfor _, v := range %s {\n%s\tb.Put%s(v)\n%s}\n", ind, expr, ind, f.Func, ind)
	case gkVecObj:
		fmt.Fprintf(b, "%sb.PutVectorHeader(len(%s))\n", ind, expr)
		fmt.Fprintf(b, "%sfor _, v := range %s {\n", ind, expr)
		arg := "v"
		if !f.Iface {
			arg = "&v"
		}
		fmt.Fprintf(b, "%s\tif err := putObj(b, l, %s); err != nil {\n%s\t\treturn err\n%s\t}\n", ind, arg, ind, ind)
		fmt.Fprintf(b, "%s}\n", ind)
	}
}

// emitDecode writes decodePriv.
func (g *goGen) emitDecode(it gen.PrivItem, d *tl.Definition, fields []gField, words map[string]int) {
	b := &g.buf
	fmt.Fprintf(b, "func (p *%s) decodePriv(b *bin.Buffer, l Layer) error {\n", it.Go)
	for name := range words {
		fmt.Fprintf(b, "\tvar %s uint32\n", strings.ToLower(pascal(name)))
	}
	idx := 0
	for _, p := range d.Params {
		if p.Flags {
			v := strings.ToLower(pascal(p.Name))
			fmt.Fprintf(b, "\t{\n\t\tx, err := b.Uint32()\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\t%s = x\n\t}\n", v)
			idx++
			continue
		}
		f := fieldByTL(fields, p.Name)
		if f == nil {
			continue
		}
		opened := false
		if f.Bit >= 0 && !f.BFlag {
			word := "flags"
			if f.Word == 1 {
				word = "flags2"
			}
			fmt.Fprintf(b, "\tif %s&(1<<%d) != 0 {\n", word, f.Bit)
			opened = true
		} else if !f.BFlag {
			b.WriteString("\t{\n")
			opened = true
		}
		switch {
		case f.BFlag:
			v := "flags"
			if f.Word == 1 {
				v = "flags2"
			}
			fmt.Fprintf(b, "\t\tp.%s = %s&(1<<%d) != 0\n", f.Go, v, f.Bit)
		case f.Kind == gkPrim:
			fmt.Fprintf(b, "\t\tx, err := b.%s()\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\tp.%s = x\n", f.Func, f.Go)
		case f.Kind == gkObj:
			fmt.Fprintf(b, "\t\tx, err := getObj(b, l)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n")
			if f.Iface {
				fmt.Fprintf(b, "\t\tp.%s = x.(%s)\n", f.Go, f.GoType)
			} else {
				fmt.Fprintf(b, "\t\ty, ok := x.(*%s)\n\t\tif !ok {\n\t\t\treturn ErrMismatch\n\t\t}\n\t\tp.%s = *y\n", f.GoType, f.Go)
			}
		case f.Kind == gkVecPrim:
			fmt.Fprintf(b, "\t\tn, err := b.VectorHeader()\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\tfor i := 0; i < n; i++ {\n\t\t\tx, err := b.%s()\n\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n\t\t\tp.%s = append(p.%s, x)\n\t\t}\n", f.Func, f.Go, f.Go)
		case f.Kind == gkVecObj:
			fmt.Fprintf(b, "\t\tn, err := b.VectorHeader()\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\tfor i := 0; i < n; i++ {\n\t\t\tx, err := getObj(b, l)\n\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
			if f.Iface {
				fmt.Fprintf(b, "\t\t\tp.%s = append(p.%s, x.(%s))\n", f.Go, f.Go, strings.TrimPrefix(f.GoType, "[]"))
			} else {
				fmt.Fprintf(b, "\t\t\ty, ok := x.(*%s)\n\t\t\tif !ok {\n\t\t\t\treturn ErrMismatch\n\t\t\t}\n\t\t\tp.%s = append(p.%s, *y)\n", strings.TrimPrefix(f.GoType, "[]"), f.Go, f.Go)
			}
			b.WriteString("\t\t}\n")
		}
		if opened {
			b.WriteString("\t}\n")
		}
	}
	b.WriteString("\treturn nil\n}\n\n")
}
