// LayGen emits the layerx package.
type LayGen struct {
	U *Uni
	G *Generator

	structs map[string]*structDef
	syms    []string
	symOf   map[string]string
	used    map[string]bool

	reports map[Layer]*ClassReport

	// custom holds emit units by id.
	custom     []*emitUnit
	unitOf     map[string]*emitUnit
	layerUnits map[Layer][]*emitUnit
	hooks      map[Layer]map[string]bool

	skipDefs map[Layer][]*layDef
	skipIdx  map[string]int
	skipDone map[string]bool

	scanCanon  map[Sym][]scanField
	scanLayers map[Layer]map[Sym][]scanField

	outBytes int
	outLines int
}

// NewLayGen builds layer generator.
func NewLayGen(g *Generator, u *Uni) *LayGen {
	l := &LayGen{
		U:       u,
		G:       g,
		structs: make(map[string]*structDef, len(g.structs)),
		symOf:   map[string]string{},
		used:    map[string]bool{},
		reports: map[Layer]*ClassReport{},
		unitOf:  map[string]*emitUnit{},
	}
	for i := range g.structs {
		s := &g.structs[i]
		l.structs[s.RawName] = s
	}
	l.syms = append(l.syms, u.CanIdx.keys...)
	sort.Strings(l.syms)
	for _, key := range l.syms {
		l.symOf[key] = l.uniqueConst("Sym" + constName(key))
	}
	for _, spec := range u.Layers {
		l.reports[spec.Meta.N] = u.Classify(spec)
	}
	return l
}

// constName converts dotted key to Go name.
func constName(key string) string {
	parts := strings.Split(key, ".")
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(pascal(p))
	}
	return b.String()
}

func (l *LayGen) uniqueConst(base string) string {
	name := base
	for i := 2; l.used[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	l.used[name] = true
	return name
}

// SymConst returns Sym constant name.
func (l *LayGen) SymConst(key string) string { return l.symOf[key] }

// file builds one source file.
type file struct {
	pkg  string
	buf  bytes.Buffer
	body strings.Builder
}

func newFile(pkg, head string) *file {
	f := &file{pkg: pkg}
	f.buf.WriteString("// Code generated by gotdgen, DO NOT EDIT.\n\n")
	f.buf.WriteString("package " + pkg + "\n\n")
	if head != "" {
		f.buf.WriteString(head)
		f.buf.WriteString("\n")
	}
	return f
}

func (f *file) p(format string, args ...any) {
	if len(args) == 0 {
		f.body.WriteString(format)
		return
	}
	fmt.Fprintf(&f.body, format, args...)
}

// raw writes text verbatim.
func (f *file) raw(s string) { f.body.WriteString(s) }

func (f *file) bytes() []byte {
	f.buf.WriteString(f.body.String())
	return f.buf.Bytes()
}

func imports(pairs ...string) string {
	if len(pairs) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("import (\n")
	for _, p := range pairs {
		b.WriteString("\t")
		b.WriteString(p)
		b.WriteString("\n")
	}
	b.WriteString(")\n")
	return b.String()
}

// Write emits all generated files.
func (l *LayGen) Write(fs FileSystem, pkg string) error {
	if err := l.Validate(); err != nil {
		return err
	}
	if err := l.buildScan(); err != nil {
		return err
	}
	l.buildUnits()
	files := []struct {
		name string
		fn   func() []byte
	}{
		{"lx_def_gen.go", func() []byte { return l.defFile(pkg) }},
		{"lx_sym_gen.go", func() []byte { return l.symFile(pkg) }},
		{"lx_ctor_gen.go", func() []byte { return l.ctorFile(pkg) }},
		{"lx_new_gen.go", func() []byte { return l.newFile(pkg) }},
		{"lx_plan_gen.go", func() []byte { return l.planFile(pkg) }},
		{"lx_put_gen.go", func() []byte { return l.putFile(pkg) }},
		{"lx_get_gen.go", func() []byte { return l.getFile(pkg) }},
		{"lx_skip_gen.go", func() []byte { return l.skipFile(pkg) }},
		{"lx_scan_gen.go", func() []byte { return l.scanFile(pkg) }},
		{"lx_wrap_gen.go", func() []byte { return l.wrapFile(pkg) }},
		{"lx_res_gen.go", func() []byte { return l.resFile(pkg) }},
		{"lx_priv_gen.go", func() []byte { return l.privFile(pkg) }},
	}
	for _, f := range files {
		data := f.fn()
		if err := fs.WriteFile(f.name, data); err != nil {
			return err
		}
		l.outBytes += len(data)
		l.outLines += bytes.Count(data, []byte("\n"))
	}
	return nil
}

// Budget bounds generated source.
const (
	budgetBytes = 16 << 20
	budgetLines = 400000
)

// OverBudget reports size violation.
func (l *LayGen) OverBudget() error {
	if l.outBytes > budgetBytes {
		return fmt.Errorf("layers: %d bytes over budget", l.outBytes)
	}
	if l.outLines > budgetLines {
		return fmt.Errorf("layers: %d lines over budget", l.outLines)
	}
	return nil
}

// Stat returns generated size.
func (l *LayGen) Stat() (nBytes, nLines int) { return l.outBytes, l.outLines }

// Validate checks decisions cover all hooks.
func (l *LayGen) Validate() error {
	for _, spec := range l.U.Layers {
		r := l.reports[spec.Meta.N]
		hooks := r.KindsOf(Hook)
		if len(hooks) == 0 {
			continue
		}
		return fmt.Errorf("layer %d: %d undecided hooks: %v", spec.Meta.N, len(hooks), hooks)
	}
	return nil
}

// defFile emits layer constants.
func (l *LayGen) defFile(pkg string) []byte {
	f := newFile(pkg, "")
	f.p("// layer numbers\n")
	f.p("const (\n")
	for _, s := range l.U.Layers {
		f.p("\tL%d Layer = %d\n", s.Meta.N, s.Meta.N)
	}
	f.p(")\n\n")
	f.p("// Canon is canonical layer.\n")
	f.p("const Canon Layer = L%d\n\n", l.U.Canon)
	f.p("// layerList lists layers.\n")
	f.p("var layerList = [...]Layer{")
	for i, s := range l.U.Layers {
		if i > 0 {
			f.p(", ")
		}
		f.p("L%d", s.Meta.N)
	}
	f.p("}\n\n")
	f.p("// Layers returns supported layers.\n")
	f.p("func Layers() []Layer { return layerList[:] }\n\n")
	f.p("// Known reports supported layer.\n")
	f.p("func Known(l Layer) bool {\n")
	f.p("\tswitch l {\n")
	for _, s := range l.U.Layers {
		f.p("\tcase L%d:\n\t\treturn true\n", s.Meta.N)
	}
	f.p("\t}\n\treturn false\n}\n")
	return f.bytes()
}

// symFile emits Sym constants.
func (l *LayGen) symFile(pkg string) []byte {
	f := newFile(pkg, "")
	f.p("// Sym is canonical type id.\n\n")
	f.p("const (\n")
	for _, key := range l.syms {
		d := l.U.CanIdx.byKey[key]
		f.p("\t%s Sym = 0x%08x\n", l.SymConst(key), d.Def.ID)
	}
	f.p(")\n\n")
	f.p("// symNames maps sym to TL name.\n")
	f.p("var symNames = map[Sym]string{\n")
	for _, key := range l.syms {
		f.p("\t%s: %q,\n", l.SymConst(key), key)
	}
	for _, it := range l.U.Priv.Custom() {
		f.p("\t%s: %q,\n", SymConstPriv(it.Go), it.Name)
	}
	f.p("}\n\n")
	f.p("// SymName returns TL name.\n")
	f.p("func SymName(s Sym) string { return symNames[s] }\n\n")
	f.p("// SymValid reports known sym.\n")
	f.p("func SymValid(s Sym) bool { _, ok := symNames[s]; return ok }\n")
	return f.bytes()
}

type ctorVar struct {
	name string
	ids  []uint32
	syms []Sym
}

// ctorFile emits wire id tables.
func (l *LayGen) ctorFile(pkg string) []byte {
	f := newFile(pkg, imports("\"sort\""))
	seen := map[string]string{}
	var vars []ctorVar
	idName := map[Layer]string{}
	symName := map[Layer]string{}

	add := func(p pairs) string {
		digest := pairsDigest(p)
		name, ok := seen[digest]
		if !ok {
			name = fmt.Sprintf("pairs%d", len(vars))
			seen[digest] = name
			vars = append(vars, ctorVar{name: name, ids: p.ids, syms: p.syms})
		}
		return name
	}
	for _, spec := range l.U.Layers {
		byID, bySym := l.pairsFor(spec)
		idName[spec.Meta.N] = add(byID)
		symName[spec.Meta.N] = add(bySym)
	}
	for _, v := range vars {
		f.p("var %sID = []uint32{\n", v.name)
		for _, id := range v.ids {
			f.p("\t0x%08x,\n", id)
		}
		f.p("}\n\n")
		f.p("var %sSym = []Sym{\n", v.name)
		for _, s := range v.syms {
			f.p("\t0x%08x,\n", uint32(s))
		}
		f.p("}\n\n")
	}
	f.p("// tableFor returns wire pair tables.\n")
	f.p("func tableFor(l Layer) (ids []uint32, syms []Sym, ok bool) {\n")
	f.p("\tswitch l {\n")
	for _, spec := range l.U.Layers {
		n := idName[spec.Meta.N]
		f.p("\tcase L%d:\n\t\treturn %sID, %sSym, true\n", spec.Meta.N, n, n)
	}
	f.p("\t}\n\treturn nil, nil, false\n}\n\n")

	f.p("// symTable returns sym pair tables.\n")
	f.p("func symTable(l Layer) (syms []Sym, ids []uint32, ok bool) {\n")
	f.p("\tswitch l {\n")
	for _, spec := range l.U.Layers {
		n := symName[spec.Meta.N]
		f.p("\tcase L%d:\n\t\treturn %sSym, %sID, true\n", spec.Meta.N, n, n)
	}
	f.p("\t}\n\treturn nil, nil, false\n}\n\n")

	f.p("// Ctor returns layer wire id.\n")
	f.p("func Ctor(l Layer, s Sym) (uint32, bool) {\n")
	f.p("\tsyms, ids, ok := symTable(l)\n")
	f.p("\tif !ok { return 0, false }\n")
	f.p("\tn := sort.Search(len(syms), func(i int) bool { return syms[i] >= s })\n")
	f.p("\tif n < len(syms) && syms[n] == s { return ids[n], true }\n")
	f.p("\treturn 0, false\n}\n\n")
	f.p("// SymOf returns sym by wire id.\n")
	f.p("func SymOf(l Layer, id uint32) (Sym, bool) {\n")
	f.p("\tids, syms, ok := tableFor(l)\n")
	f.p("\tif !ok { return 0, false }\n")
	f.p("\tn := sort.Search(len(ids), func(i int) bool { return ids[i] >= id })\n")
	f.p("\tif n < len(ids) && ids[n] == id { return syms[n], true }\n")
	f.p("\treturn 0, false\n}\n")
	return f.bytes()
}

// newFile emits constructor switch.
func (l *LayGen) newFile(pkg string) []byte {
	f := newFile(pkg, imports(
		fmt.Sprintf("%q", "github.com/gotd/td/bin"),
		"",
		fmt.Sprintf("%q", "github.com/gotd/td/tg"),
	)+"\nvar (\n\t_ = bin.Buffer{}\n\t_ = tg.User{}\n)\n")
	f.p("// newSym allocates canonical value.\n")
	f.p("func newSym(s Sym) bin.Object {\n")
	f.p("\tswitch s {\n")
	for _, key := range l.syms {
		sd, ok := l.structs[key]
		if !ok {
			f.p("\tcase %s:\n\t\treturn nil\n", l.SymConst(key))
			continue
		}
		f.p("\tcase %s:\n\t\treturn new(tg.%s)\n", l.SymConst(key), sd.Name)
	}
	f.p("\t}\n\treturn nil\n}\n")
	return f.bytes()
}

// planFile emits dispatch.
func (l *LayGen) planFile(pkg string) []byte {
	f := newFile(pkg, imports(
		fmt.Sprintf("%q", "fmt"),
		"",
		fmt.Sprintf("%q", "github.com/gotd/td/bin"),
		"",
		fmt.Sprintf("%q", "github.com/gotd/td/tg"),
	)+"\nvar (\n\t_ = fmt.Stringer(nil)\n\t_ = bin.Buffer{}\n\t_ = tg.User{}\n)\n")
	f.p("// putAt writes id and body.\n")
	f.p("func putAt(b *bin.Buffer, l Layer, s Sym, v bin.Object) error {\n")
	f.p("\tif IsPriv(s) {\n\t\treturn putPriv(b, l, s, v)\n\t}\n")
	f.p("\tswitch l {\n")
	for _, spec := range l.U.Layers {
		units := l.unitsOf(spec.Meta.N)
		hooks := l.hooks[spec.Meta.N]
		if len(units) == 0 && len(hooks) == 0 {
			continue
		}
		f.p("\tcase L%d:\n\t\tswitch s {\n", spec.Meta.N)
		for _, u := range units {
			f.p("\t\tcase %s:\n", l.SymConst(u.key))
			f.p("\t\t\tif err := putWithID(b, l, s); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
			f.p("\t\t\treturn %s(b, l, v.(*tg.%s))\n", u.putName, u.goName)
		}
		for _, key := range sortedKeys(hooks) {
			f.p("\t\tcase %s:\n\t\t\treturn ErrHook\n", l.SymConst(key))
		}
		f.p("\t\t}\n")
	}
	f.p("\t}\n\treturn putCanon(b, l, s, v)\n}\n\n")

	f.p("// getAt decodes body by sym.\n")
	f.p("func getAt(b *bin.Buffer, l Layer, s Sym) (bin.Object, error) {\n")
	f.p("\tif IsPriv(s) {\n\t\treturn getPriv(b, l, s)\n\t}\n")
	f.p("\tswitch l {\n")
	for _, spec := range l.U.Layers {
		units := l.unitsOf(spec.Meta.N)
		hooks := l.hooks[spec.Meta.N]
		if len(units) == 0 && len(hooks) == 0 {
			continue
		}
		f.p("\tcase L%d:\n\t\tswitch s {\n", spec.Meta.N)
		for _, u := range units {
			f.p("\t\tcase %s:\n", l.SymConst(u.key))
			f.p("\t\t\tv := new(tg.%s)\n", u.goName)
			f.p("\t\t\tif err := %s(b, l, v); err != nil {\n", u.getName)
			f.p("\t\t\t\treturn nil, err\n\t\t\t}\n")
			f.p("\t\t\treturn v, nil\n")
		}
		for _, key := range sortedKeys(hooks) {
			f.p("\t\tcase %s:\n\t\t\treturn nil, ErrHook\n", l.SymConst(key))
		}
		f.p("\t\t}\n")
	}
	f.p("\t}\n\treturn getCanon(b, l, s)\n}\n\n")

	f.p("// customAt reports layer codec.\n")
	f.p("func customAt(l Layer, s Sym) bool {\n\tswitch l {\n")
	for _, spec := range l.U.Layers {
		units := l.unitsOf(spec.Meta.N)
		if len(units) == 0 {
			continue
		}
		f.p("\tcase L%d:\n\t\tswitch s {\n", spec.Meta.N)
		for _, u := range units {
			f.p("\t\tcase %s:\n\t\t\treturn true\n", l.SymConst(u.key))
		}
		f.p("\t\t}\n")
	}
	f.p("\t}\n\treturn false\n}\n\n")

	f.p("// putCanon writes canonical body.\n")
	f.p("func putCanon(b *bin.Buffer, l Layer, s Sym, v bin.Object) error {\n")
	f.p("\tid, ok := Ctor(l, s)\n")
	f.raw("\tif !ok { return fmt.Errorf(\"%w: %s in layer %d\", ErrAbsent, SymName(s), l) }\n")
	f.p("\tb.PutID(id)\n")
	f.p("\te, ok := v.(bin.BareEncoder)\n")
	f.raw("\tif !ok { return fmt.Errorf(\"%w: %s\", ErrNoPlan, SymName(s)) }\n")
	f.p("\treturn e.EncodeBare(b)\n}\n\n")

	f.p("// getCanon decodes canonical body.\n")
	f.p("func getCanon(b *bin.Buffer, l Layer, s Sym) (bin.Object, error) {\n")
	f.p("\tv := newSym(s)\n")
	f.raw("\tif v == nil { return nil, fmt.Errorf(\"%w: %s\", ErrNoPlan, SymName(s)) }\n")
	f.p("\tif _, ok := Ctor(l, s); !ok {\n")
	f.raw("\t\treturn nil, fmt.Errorf(\"%w: %s in layer %d\", ErrAbsent, SymName(s), l)\n\t}\n")
	f.p("\td, ok := v.(bin.BareDecoder)\n")
	f.raw("\tif !ok { return nil, fmt.Errorf(\"%w: %s\", ErrNoPlan, SymName(s)) }\n")
	f.p("\tif err := d.DecodeBare(b); err != nil { return nil, err }\n")
	f.p("\treturn v, nil\n}\n")
	return f.bytes()
}

// pairs is a wire table.
type pairs struct {
	ids  []uint32
	syms []Sym
}

// pairsFor builds both orderings.
func (l *LayGen) pairsFor(spec *LayerSpec) (byID, bySym pairs) {
	type kv struct {
		id uint32
		s  Sym
	}
	var list []kv
	for _, k := range l.U.CanIdx.keys {
		can := l.U.CanIdx.byKey[k]
		lay, ok := spec.Idx.Get(k)
		if !ok {
			continue
		}
		list = append(list, kv{id: lay.Def.ID, s: Sym(can.Def.ID)})
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].id == list[j].id {
			return list[i].s < list[j].s
		}
		return list[i].id < list[j].id
	})
	for _, e := range list {
		byID.ids = append(byID.ids, e.id)
		byID.syms = append(byID.syms, e.s)
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].s == list[j].s {
			return list[i].id < list[j].id
		}
		return list[i].s < list[j].s
	})
	for _, e := range list {
		bySym.syms = append(bySym.syms, e.s)
		bySym.ids = append(bySym.ids, e.id)
	}
	return byID, bySym
}

func pairsDigest(p pairs) string {
	var b strings.Builder
	for i := range p.ids {
		fmt.Fprintf(&b, "%08x:%08x;", p.ids[i], uint32(p.syms[i]))
	}
	return b.String()
}
